"""Regenerate docs/ENDPOINTS.md from the running code.

    venv/Scripts/python -m pytest          # records what the suite exercises
    venv/Scripts/python scripts/gen_endpoints.py

Three sources, none of them hand-maintained:
  * routes and auth  -- Flask's url_map and each view's decorators
  * test coverage    -- tests/.route_coverage.json, written by the test suite
  * frontend callers -- apiClient / adminApi calls found in frontend/src
"""
import inspect
import json
import os
import pathlib
import re
import sys

BACKEND = pathlib.Path(__file__).resolve().parent.parent
ROOT = BACKEND.parent
sys.path.insert(0, str(BACKEND))
os.environ.setdefault("FLASK_ENV", "testing")

from app import create_app  # noqa: E402

COVERAGE = BACKEND / "tests" / ".route_coverage.json"
FRONTEND_SRC = ROOT / "frontend" / "src"
OUT = ROOT / "docs" / "ENDPOINTS.md"

# Routes with no storefront/admin screen by design.
NO_SCREEN_BY_DESIGN = {
    ("GET", "/api/health"): "platform health check",
    ("POST", "/api/payments/webhook"): "called by Razorpay",
    ("GET", "/sitemap.xml"): "crawlers",
    ("GET", "/robots.txt"): "crawlers",
    ("POST", "/api/newsletter/unsubscribe"): "linked from emails",
    ("POST", "/api/auth/refresh"): "apiClient interceptor",
    ("POST", "/api/admin/auth/refresh"): "adminApi interceptor",
}

QUOTES = "`'\""
CALL_RE = re.compile(
    r"(?:apiClient|adminApi)\s*\.\s*(get|post|put|patch|delete)\(\s*"
    rf"[{QUOTES}]([^{QUOTES}]+)[{QUOTES}]",
    re.S,
)
# List pages load through the useAdminList(url, ...) hook rather than calling
# adminApi.get themselves.
HOOK_RE = re.compile(rf"useAdminList\(\s*[{QUOTES}]([^{QUOTES}]+)[{QUOTES}]", re.S)
TEMPLATE_VAR = re.compile(r"\$\{[^}]+\}")


def auth_of(view, rule):
    head = inspect.getsource(view).split("def ", 1)[0]
    if "@master_required" in head:
        return "master admin"
    if "@admin_required" in head:
        return "admin"
    if "jwt_required(refresh=True" in head or rule.endswith("/auth/refresh"):
        return "refresh cookie"
    if "@jwt_required" in head:
        return "customer"
    if rule == "/api/payments/webhook":
        return "public (signed)"
    return "public"


def frontend_calls():
    """{(METHOD, path with <p> placeholders): {files}} for every frontend call."""
    calls = {}
    for path in FRONTEND_SRC.rglob("*.js*"):
        text = path.read_text(encoding="utf-8")
        found = CALL_RE.findall(text) + [("get", url) for url in HOOK_RE.findall(text)]
        for method, url in found:
            url = "/api" + TEMPLATE_VAR.sub("<p>", url.split("?")[0])
            rel = path.relative_to(FRONTEND_SRC).as_posix()
            calls.setdefault((method.upper(), url), set()).add(rel)
    return calls


def rule_pattern(rule):
    return re.compile("^" + re.sub(r"<[^>]+>", "[^/]+", rule) + "$")


def succeeded(statuses):
    return any(200 <= s < 300 for s in statuses)


def main():
    if not COVERAGE.exists():
        sys.exit("Run pytest first: tests/.route_coverage.json is missing.")
    seen = {}
    for method, rule, status in json.loads(COVERAGE.read_text()):
        seen.setdefault((method, rule), set()).add(status)

    calls = frontend_calls()
    matched_calls = set()

    app = create_app()
    rows = []
    for rule in app.url_map.iter_rules():
        if rule.endpoint == "static":
            continue
        view = inspect.unwrap(app.view_functions[rule.endpoint])
        pattern = rule_pattern(rule.rule)
        for method in sorted(rule.methods - {"HEAD", "OPTIONS"}):
            users = set()
            for (c_method, c_url), files in calls.items():
                if c_method == method and pattern.match(c_url):
                    users |= files
                    matched_calls.add((c_method, c_url))
            rows.append({
                "method": method,
                "path": rule.rule,
                "auth": auth_of(view, rule.rule),
                "statuses": sorted(seen.get((method, rule.rule), ())),
                "users": sorted(users),
            })
    rows.sort(key=lambda r: (r["path"], r["method"]))

    def screen_cell(row):
        if row["users"]:
            names = sorted({
                u.rsplit("/index", 1)[0].split("/")[-1].split(".")[0]
                for u in row["users"]
            })
            return ", ".join(names)
        why = NO_SCREEN_BY_DESIGN.get((row["method"], row["path"]))
        return f"n/a ({why})" if why else "**none**"

    untested = [r for r in rows if not succeeded(r["statuses"])]
    unused = [
        r for r in rows
        if not r["users"] and (r["method"], r["path"]) not in NO_SCREEN_BY_DESIGN
    ]
    orphans = sorted(set(calls) - matched_calls)

    out = [
        "# API endpoints",
        "",
        "Generated by `backend/scripts/gen_endpoints.py` — do not edit by hand.",
        "Run `pytest`, then the script, to refresh it.",
        "",
        f"**{len(rows)} routes** · {len(rows) - len(untested)} with a passing "
        f"success test · {len(untested)} without · {len(unused)} with no "
        f"frontend caller · {len(orphans)} frontend calls with no route.",
        "",
        "- **Status** is ✅ when the test suite gets a 2xx from the route.",
        "- **Tested responses** lists every status code the suite observed, so "
        "401 / 403 / 404 / 422 coverage is visible per route.",
        "- Auth, role, unknown-id and malformed-body behaviour is also enforced "
        "for *every* route by `tests/test_route_contracts.py`.",
        "",
        "| Method | Path | Auth | Status | Tested responses | Used by |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        codes = " ".join(str(s) for s in r["statuses"]) or "none"
        status = "✅" if succeeded(r["statuses"]) else "❌ no passing test"
        out.append(
            f"| {r['method']} | `{r['path']}` | {r['auth']} | {status} | "
            f"{codes} | {screen_cell(r)} |"
        )

    out += ["", "## Frontend calls with no backend route", ""]
    out += [
        f"- `{m} {u}` — {', '.join(sorted(calls[(m, u)]))}" for m, u in orphans
    ] or ["None."]
    out += ["", "## Routes no screen uses", ""]
    out += [
        f"- `{r['method']} {r['path']}` ({r['auth']})" for r in unused
    ] or ["None."]
    out.append("")

    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(rows)} routes, {len(untested)} untested, {len(unused)} unused, "
          f"{len(orphans)} orphan frontend calls")
    for r in untested:
        print("  untested:", r["method"], r["path"])


if __name__ == "__main__":
    main()
