-- Migration: operational bookkeeping tables.
--
-- webhook_events  one row per provider event already handled, so a retried
--                 Razorpay delivery is acknowledged without being acted on twice.
-- job_runs        history of scheduled jobs (reconcile-payments), shown on the
--                 admin System Health panel.
--
-- Safe to run more than once.

CREATE TABLE IF NOT EXISTS public.webhook_events (
    event_id text NOT NULL,
    source text NOT NULL,
    kind text,
    received_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT webhook_events_pkey PRIMARY KEY (event_id)
);

CREATE INDEX IF NOT EXISTS idx_webhook_events_received_at
    ON public.webhook_events USING btree (received_at);

CREATE TABLE IF NOT EXISTS public.job_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL,
    started_at timestamp with time zone DEFAULT now() NOT NULL,
    finished_at timestamp with time zone,
    ok boolean DEFAULT true NOT NULL,
    summary jsonb DEFAULT '{}'::jsonb NOT NULL,
    CONSTRAINT job_runs_pkey PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_job_runs_name_started
    ON public.job_runs USING btree (name, started_at DESC);
